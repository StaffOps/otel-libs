#!/usr/bin/env bash
# Regenerate python/demo/requirements.lock from requirements.in (Docker only).
#
#   python/demo/lock.sh          # rewrite the lock (resolves the newest allowed versions)
#
# pip-compile resolves the local helper (python/, extras redis+sql) together
# with the apps' dependencies for linux/amd64 on the images' Python, with
# hashes; the helper's own file:// line is then dropped, because the
# Dockerfiles install it from the local tree with --no-deps after the lock.
set -euo pipefail

root="$(cd "$(dirname "$0")/../.." && pwd)"
PY_IMAGE="${PY_IMAGE:-python:3.11-slim@sha256:07d4824036af339fa1b6ef769cc99d9c10a141769538b52b3b597c84f7a7b535}"
PIP_TOOLS="pip-tools==7.5.2"

out="$(docker run --rm --platform linux/amd64 -e PIP_DISABLE_PIP_VERSION_CHECK=1 \
  -v "$root:/work:ro" "$PY_IMAGE" sh -ec "
    pip install -q '$PIP_TOOLS' >/dev/null
    cp /work/python/demo/requirements.in /tmp/requirements.in
    cd /tmp
    pip-compile -q --generate-hashes --allow-unsafe --strip-extras --no-header \
      --no-emit-index-url --output-file=- requirements.in
  ")"

# Drop the helper's own entry (its line, its continuation lines and the
# unhashed-URL warning pip-compile writes above it).
body="$(printf '%s\n' "$out" | awk '
  /^# WARNING: pip install will require the following package to be hashed/ { next }
  /^# Consider using a hashable URL/ { next }
  /^staffops-otel-helper/ { skip = 1; next }
  skip && /^[[:space:]]/ { next }
  { skip = 0; print }
')"

header="# Generated by python/demo/lock.sh from requirements.in (pip-compile --generate-hashes,
# linux/amd64, ${PY_IMAGE}). Do not edit; staffops-otel-helper is installed from the
# local tree with --no-deps after this file.
"
new="${header}${body}"

lock="$root/python/demo/requirements.lock"
printf '%s\n' "$new" >"$lock"
echo "wrote $lock"
